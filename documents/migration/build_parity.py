"""Build 03-FEATURE-PARITY.md: one row per requirement R1..Rmax with its
status in the Rust core. Titles come from the spec (CHANGELOG_TECHNICAL.md,
R1-R293) and requirements/*.md (R223 on); statuses from parity-status.yaml.
Every number without a status is NOT_STARTED. Run from anywhere:

    python documents/migration/build_parity.py          # rewrite the table
    python documents/migration/build_parity.py --check  # exit 1 if stale
"""

import re
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = HERE / "03-FEATURE-PARITY.md"
STATUSES = ("PORTED", "PARTIAL", "NOT_STARTED", "NOT_APPLICABLE")
_HEAD = re.compile(r"^\s*(?:[-*]|\d+\.|#+)\s+\*{0,2}(R(\d+)[a-z]?)\b\.?\*{0,2}\s*(?:—|-|:)?\s*([^\n]*)", re.M)


def _clean(title: str) -> str:
    title = re.sub(r"\*\*|\*|`", "", title).strip(" .—-")
    title = re.split(r"\s\((?:owner|user|found|after)\b", title)[0]
    return (title[:110] + "…") if len(title) > 111 else title


def titles() -> dict[int, str]:
    out: dict[int, str] = {}
    sources = [ROOT / "documents" / "CHANGELOG_TECHNICAL.md", *sorted((ROOT / "requirements").glob("*.md"))]
    for src in sources:  # later files (the restated rules) win
        for m in _HEAD.finditer(src.read_text(encoding="utf-8")):
            n, title = int(m.group(2)), _clean(m.group(3))
            if title and (n not in out or src.parent.name == "requirements"):
                out[n] = title
    return out


def commit_titles() -> dict[int, str]:
    """For numbers with no written entry: the subject of the oldest commit
    that names them (stable, since history only grows). Empty without git."""
    try:
        log = subprocess.run(["git", "log", "--reverse", "--format=%s"], cwd=ROOT, capture_output=True,
                             text=True, timeout=60, check=True).stdout
    except (OSError, subprocess.SubprocessError):
        return {}
    out: dict[int, str] = {}
    for subject in log.splitlines():
        for n in re.findall(r"\bR(\d+)\b", subject):
            out.setdefault(int(n), "commit: " + _clean(subject))
    return out


def highest() -> int:
    text = (ROOT / "REQUIREMENTS.md").read_text(encoding="utf-8")
    for src in (ROOT / "requirements").glob("*.md"):
        text += src.read_text(encoding="utf-8")
    return max(int(n) for n in re.findall(r"\bR(\d+)\b", text))


def statuses() -> dict[int, tuple[str, str]]:
    raw = yaml.safe_load((HERE / "parity-status.yaml").read_text(encoding="utf-8")) or {}
    out = {}
    for key, val in raw.items():
        status, _, note = str(val).partition(":")
        status = status.strip()
        if status not in STATUSES:
            raise SystemExit(f"parity-status.yaml: {key}: unknown status {status!r}")
        out[int(str(key).lstrip("R"))] = (status, note.strip())
    return out


def compat_tests() -> dict[int, list[str]]:
    """N4: which differential tests (tests/test_rust_*.py) name each requirement."""
    out: dict[int, list[str]] = {}
    for f in sorted((ROOT / "tests").glob("test_rust_*.py")):
        for n in sorted({int(x) for x in re.findall(r"\bR(\d+)\b", f.read_text(encoding="utf-8"))}):
            out.setdefault(n, []).append(f.stem.removeprefix("test_rust_"))
    return out


def coverage(marks, tests) -> dict[int, list[str]]:
    """A requirement is covered by a test that names it, or names the port (the R<n> its note cites)."""
    out = {}
    for n, (_status, note) in marks.items():
        names = list(tests.get(n, []))
        for cited in re.findall(r"\bR(\d+)\b", note):
            names += [t for t in tests.get(int(cited), []) if t not in names]
        out[n] = names
    return out


def uncovered() -> list[int]:
    marks = statuses()
    cov = coverage(marks, compat_tests())
    return [n for n, (status, _) in sorted(marks.items()) if status in ("PORTED", "PARTIAL") and not cov[n]]


def render() -> str:
    top, names, marks = highest(), titles(), statuses()
    cov = coverage(marks, compat_tests())
    names = {**commit_titles(), **names}
    counts = dict.fromkeys(STATUSES, 0)
    rows = []
    for n in range(1, top + 1):
        status, note = marks.get(n, ("NOT_STARTED", ""))
        counts[status] += 1
        title = names.get(n, "(no written entry: see the git log for its commit)").replace("|", "\\|")
        tests = ", ".join(cov.get(n, []))
        rows.append(f"| R{n} | {title} | {status} | {tests} | {note.replace('|', '/')} |")
    summary = ", ".join(f"{k} {v}" for k, v in counts.items())
    return (
        "# Feature parity: Python Aurora → Rust core\n\n"
        "Generated by `documents/migration/build_parity.py` from the requirement files and\n"
        "`parity-status.yaml`. Do not edit by hand: change the status file and rebuild.\n\n"
        f"Requirements R1–R{top}: {summary}.\n\n"
        "PORTED means the Rust core does it and a test shows it; PARTIAL means part of it is\n"
        "there (the note says what is missing); NOT_APPLICABLE is a removed or Python-only\n"
        "requirement. The Compat test column names the differential tests\n"
        "(`tests/test_rust_<name>.py`) that check it against Python (N4): PORTED and PARTIAL\n"
        "rows must have one, and `--check` fails when one does not.\n\n"
        "| Req | What | Rust core | Compat test | Note |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n"
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if missing := uncovered():
            sys.exit("ported without a differential test: " + ", ".join(f"R{n}" for n in missing))
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        sys.exit(0 if current == text else "03-FEATURE-PARITY.md is stale: run build_parity.py")
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
